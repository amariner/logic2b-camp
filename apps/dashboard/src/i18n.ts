type Key = keyof typeof es;

export function t(key: Key, vars?: Record<string, string | number>): string {
  const raw: string = es[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : raw;
}

/** Clave construida desde datos (conceptos del desglose): con fallback, sin romper el tipado. */
export function tDyn(key: string, fallback: string): string {
  return (es as Record<string, string>)[key] ?? fallback;
}
